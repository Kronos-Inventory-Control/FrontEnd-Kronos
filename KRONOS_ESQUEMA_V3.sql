-- 9.2 Compra del cliente: crea ventas + detalleVentas en UNA transacción.
--     Los triggers hacen el resto (salida de inventario, movimiento, alertas).
create or replace function public.registrar_venta(
  p_items jsonb,
  p_metodo_pago text default 'Contra entrega',
  p_comprobante text default null
) returns integer language plpgsql security definer set search_path = public as $$
declare
  v_cliente integer := public.kronos_mi_cliente();
  v_venta   integer;
  v_item    jsonb;
  v_inv     "inventarios"%rowtype;
  v_cant    integer;
  v_total   numeric(12,2) := 0;
begin
  if v_cliente is null then
    raise exception 'Solo las cuentas de cliente pueden registrar compras.';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío.';
  end if;

  insert into "ventas"("descuento","fechaVenta","estado","totalVenta","comprobantePago","metodoPago","cliente_idCliente")
  values (0, now(), 'pendiente', 0, p_comprobante, coalesce(p_metodo_pago, 'Contra entrega'), v_cliente)
  returning "idVenta" into v_venta;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_cant := (v_item->>'cantidad')::integer;
    if v_cant is null or v_cant <= 0 then raise exception 'Cantidad no válida.'; end if;

    select * into v_inv from "inventarios" where "id" = (v_item->>'id')::integer for update;
    if not found then raise exception 'Un producto del carrito ya no existe.'; end if;
    if v_inv."stock" < v_cant then
      raise exception 'Stock insuficiente de "%": solo hay % disponible(s).', v_inv."nombre", v_inv."stock";
    end if;

    insert into "detalleVentas"("subTotal","cantidad","precioUnitario","venta_idVenta","inventario_codInventario")
    values (v_cant * v_inv."precioVenta", v_cant, v_inv."precioVenta", v_venta, v_inv."id");

    v_total := v_total + v_cant * v_inv."precioVenta";
  end loop;

  update "ventas"   set "totalVenta" = v_total where "idVenta" = v_venta;
  update "clientes" set "carritoActivo" = false where "idCliente" = v_cliente;
  return v_venta;
end $$;
grant execute on function public.registrar_venta(jsonb, text, text) to authenticated;

-- 9.3 Eliminar categoría: los productos pasan a "Sin categoría" y se borra (atómico)
create or replace function public.eliminar_categoria(p_categoria integer)
returns integer language plpgsql set search_path = public as $$
declare
  v_sin integer;
  v_mov integer;
begin
  if not public.kronos_es_staff() then
    raise exception 'Solo el jefe puede eliminar categorías.';
  end if;
  select "idCategoria" into v_sin from "categorias" where "nombreCategoria" = 'Sin categoría';
  if v_sin is null then
    insert into "categorias"("nombreCategoria") values ('Sin categoría') returning "idCategoria" into v_sin;
  end if;
  if p_categoria = v_sin then
    raise exception 'La categoría "Sin categoría" no se puede eliminar.';
  end if;

  update "inventarios" set "categoria_idCategoria" = v_sin where "categoria_idCategoria" = p_categoria;
  get diagnostics v_mov = row_count;

  delete from "categorias" where "idCategoria" = p_categoria;
  if not found then
    raise exception 'La categoría no existe o no tienes permiso para eliminarla.';
  end if;
  return v_mov;
end $$;
grant execute on function public.eliminar_categoria(integer) to authenticated;

-- 9.4 Proveedores: usuario (rol Proveedor) + dirección + ficha, de una vez
create or replace function public.crear_proveedor(
  p_identificacion bigint, p_nombre text, p_apellidos text, p_correo text,
  p_telefono text, p_direccion text, p_tipo_producto text
) returns integer language plpgsql set search_path = public as $$
declare
  v_dir  integer;
  v_prov integer;
begin
  if not public.kronos_es_staff() then
    raise exception 'Solo el jefe puede registrar proveedores.';
  end if;
  if nullif(btrim(coalesce(p_direccion,'')), '') is not null then
    insert into "direcciones"("ciudad","direccionCompleta") values ('Bogotá', btrim(p_direccion))
    returning "idDireccion" into v_dir;
  end if;
  insert into "usuarios"("identificacion","nombre","apellidos","correoElectronico","telefono","rol_idRol","direccion_idDireccion")
  values (p_identificacion, btrim(p_nombre), coalesce(btrim(p_apellidos), ''), btrim(p_correo),
          nullif(btrim(coalesce(p_telefono,'')), ''),
          (select "idRol" from "roles" where lower("nombreRol") = 'proveedor'), v_dir);
  insert into "proveedores"("tipoProducto","usuario_identificacion")
  values (nullif(btrim(coalesce(p_tipo_producto,'')), ''), p_identificacion)
  returning "idProveedor" into v_prov;
  return v_prov;
end $$;
grant execute on function public.crear_proveedor(bigint, text, text, text, text, text, text) to authenticated;

create or replace function public.actualizar_proveedor(
  p_proveedor integer, p_identificacion bigint, p_nombre text, p_apellidos text, p_correo text,
  p_telefono text, p_direccion text, p_tipo_producto text
) returns void language plpgsql set search_path = public as $$
declare
  v_ident bigint;
  v_dir   integer;
begin
  if not public.kronos_es_staff() then
    raise exception 'Solo el jefe puede editar proveedores.';
  end if;
  select "usuario_identificacion" into v_ident from "proveedores" where "idProveedor" = p_proveedor;
  if v_ident is null then raise exception 'El proveedor no existe.'; end if;

  select "direccion_idDireccion" into v_dir from "usuarios" where "identificacion" = v_ident;
  if v_dir is null and nullif(btrim(coalesce(p_direccion,'')), '') is not null then
    insert into "direcciones"("ciudad","direccionCompleta") values ('Bogotá', btrim(p_direccion))
    returning "idDireccion" into v_dir;
  elsif v_dir is not null then
    update "direcciones" set "direccionCompleta" = nullif(btrim(coalesce(p_direccion,'')), '') where "idDireccion" = v_dir;
  end if;

  update "usuarios" set
    "identificacion" = p_identificacion, "nombre" = btrim(p_nombre), "apellidos" = coalesce(btrim(p_apellidos), ''),
    "correoElectronico" = btrim(p_correo), "telefono" = nullif(btrim(coalesce(p_telefono,'')), ''),
    "direccion_idDireccion" = v_dir
  where "identificacion" = v_ident;

  update "proveedores" set "tipoProducto" = nullif(btrim(coalesce(p_tipo_producto,'')), '')
  where "idProveedor" = p_proveedor;
end $$;
grant execute on function public.actualizar_proveedor(integer, bigint, text, text, text, text, text, text) to authenticated;

create or replace function public.eliminar_proveedor(p_proveedor integer)
returns void language plpgsql set search_path = public as $$
declare
  v_ident bigint;
  v_auth  uuid;
begin
  if not public.kronos_es_staff() then
    raise exception 'Solo el jefe puede eliminar proveedores.';
  end if;
  select p."usuario_identificacion", u."auth_id" into v_ident, v_auth
  from "proveedores" p join "usuarios" u on u."identificacion" = p."usuario_identificacion"
  where p."idProveedor" = p_proveedor;
  if v_ident is null then raise exception 'El proveedor no existe.'; end if;

  delete from "proveedores" where "idProveedor" = p_proveedor;
  -- Si todavía no tenía cuenta de acceso se borra también su usuario;
  -- si ya la tenía, el usuario queda (y las órdenes viejas conservan el historial).
  if v_auth is null then
    delete from "usuarios" where "identificacion" = v_ident;
  end if;
end $$;
grant execute on function public.eliminar_proveedor(integer) to authenticated;


