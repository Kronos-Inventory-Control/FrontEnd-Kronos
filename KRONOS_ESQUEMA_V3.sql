  return new;
end $$;

create trigger trg_detalle_venta_salida
  after insert on "detalleVentas"
  for each row execute function public.kronos_detalle_venta_salida();

-- 8.6 Venta rechazada -> devuelve el stock (movimiento tipo 5)
create or replace function public.kronos_venta_rechazada()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new."estado" = 'rechazada' and old."estado" is distinct from 'rechazada' then
    insert into "movimientos"("fechaMovimiento","precioUnitario","cantidad","subtotal","tipoMovimiento",
                              "usuario_identificacion","inventario_codInventario","detalleVenta_idDetalleVenta")
    select now(), d."precioUnitario", d."cantidad", d."subTotal", 5,
