-- 7) FUNCIONES AUXILIARES (quién soy / qué rol tengo)
--    SECURITY DEFINER: leen usuarios sin pasar por RLS (evita recursión).
-- ============================================================
create or replace function public.kronos_mi_identificacion()
returns bigint language sql stable security definer set search_path = public as $$
  select u."identificacion" from "usuarios" u where u."auth_id" = auth.uid() limit 1
$$;

create or replace function public.kronos_mi_rol()
returns text language sql stable security definer set search_path = public as $$
  select lower(r."nombreRol")
  from "usuarios" u join "roles" r on r."idRol" = u."rol_idRol"
  where u."auth_id" = auth.uid() limit 1
$$;

create or replace function public.kronos_es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.kronos_mi_rol() in ('administrador','empleado'), false)
$$;

create or replace function public.kronos_mi_cliente()
returns integer language sql stable security definer set search_path = public as $$
  select c."idCliente" from "clientes" c
  join "usuarios" u on u."identificacion" = c."usuario_identificacion"
  where u."auth_id" = auth.uid() limit 1
$$;

create or replace function public.kronos_mi_proveedor()
returns integer language sql stable security definer set search_path = public as $$
  select p."idProveedor" from "proveedores" p
  join "usuarios" u on u."identificacion" = p."usuario_identificacion"
  where u."auth_id" = auth.uid() limit 1
$$;

-- ¿Este detalle de venta es de una compra mía (cliente)?
create or replace function public.kronos_detalle_es_mio(p_detalle integer)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from "detalleVentas" d join "ventas" v on v."idVenta" = d."venta_idVenta"
    where d."idDetalleVenta" = p_detalle and v."cliente_idCliente" = public.kronos_mi_cliente()
  )
$$;

-- ¿Este detalle de venta es de un producto que me compraron / surto yo (proveedor)?
create or replace function public.kronos_detalle_es_de_mi_proveedor(p_detalle integer)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from "detalleVentas" d
    join "ordenesCompra" o on o."inventario_codInventario" = d."inventario_codInventario"
    where d."idDetalleVenta" = p_detalle and o."proveedor_idProveedor" = public.kronos_mi_proveedor()
  )
$$;

create or replace function public.kronos_garantia_es_mia(p_garantia integer)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from "garantias" g where g."idGarantia" = p_garantia
                 and public.kronos_detalle_es_mio(g."detalleventa_idDetalleVenta"))
$$;

create or replace function public.kronos_garantia_es_de_mi_proveedor(p_garantia integer)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from "garantias" g where g."idGarantia" = p_garantia
                 and public.kronos_detalle_es_de_mi_proveedor(g."detalleventa_idDetalleVenta"))
$$;


-- Compras (detalle de venta + venta + cliente + producto) que el usuario actual
-- tiene derecho a ver: staff = todas, cliente = las suyas, proveedor = las de
-- los productos que él surte (solo con el nombre del cliente, sin más datos
-- personales). El front la usa para pedidos, historial y garantías.
create or replace function public.kronos_detalles_visibles()
returns table (
  "idDetalleVenta" integer, "idVenta" integer, "idCliente" integer,
  "nombreCliente" text, "correoCliente" text, "fechaVenta" timestamptz,
  "estadoVenta" text, "observacionVenta" text, "metodoPago" text,
  "cantidad" integer, "precioUnitario" numeric, "subTotal" numeric,
  "inventario" integer, "nombreProducto" text
) language sql stable security definer set search_path = public as $$
  select d."idDetalleVenta", v."idVenta", c."idCliente",
         btrim(u."nombre" || ' ' || u."apellidos")::text,
         case when public.kronos_es_staff() or v."cliente_idCliente" = public.kronos_mi_cliente()
              then u."correoElectronico"::text else null end,
         v."fechaVenta", v."estado"::text, v."observacion"::text, v."metodoPago"::text,
         d."cantidad", d."precioUnitario"::numeric, d."subTotal"::numeric,
         d."inventario_codInventario", i."nombre"::text
  from "detalleVentas" d
  join "ventas"      v on v."idVenta" = d."venta_idVenta"
  join "clientes"    c on c."idCliente" = v."cliente_idCliente"
  join "usuarios"    u on u."identificacion" = c."usuario_identificacion"
  join "inventarios" i on i."id" = d."inventario_codInventario"
  where public.kronos_es_staff()
     or v."cliente_idCliente" = public.kronos_mi_cliente()
     or public.kronos_detalle_es_de_mi_proveedor(d."idDetalleVenta")
$$;
grant execute on function public.kronos_detalles_visibles() to authenticated;


