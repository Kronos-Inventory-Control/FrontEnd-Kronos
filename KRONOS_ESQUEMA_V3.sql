-- 8.1 Registro de cuenta nueva en Auth -> crea usuarios (+ direcciones + clientes)
--     El front manda los datos en signUp(options.data). Si el correo ya
--     existe en `usuarios` sin cuenta (p. ej. un proveedor registrado por
--     el jefe) NO se crea uno nuevo: se vincula la cuenta a esa fila.
create or replace function public.kronos_handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_meta  jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_ident bigint;
  v_dir   integer;
  v_prev  bigint;
begin
  select u."identificacion" into v_prev
  from "usuarios" u
  where lower(u."correoElectronico") = lower(new.email) and u."auth_id" is null
  limit 1;

  if v_prev is not null then
    update "usuarios" set "auth_id" = new.id where "identificacion" = v_prev;
    return new;
  end if;

  begin
    v_ident := nullif(regexp_replace(coalesce(v_meta->>'identificacion', ''), '\D', '', 'g'), '')::bigint;
  exception when others then
    v_ident := null;
  end;

  -- Cuentas creadas a mano desde el panel de Supabase (sin datos): se
  -- enlazan después con el bloque "ADMIN INICIAL" del final de este script.
  if v_ident is null then
    return new;
  end if;

  insert into "direcciones"("barrio","ciudad","localidad","direccionCompleta")
  values (nullif(v_meta->>'barrio',''), coalesce(nullif(v_meta->>'ciudad',''), 'Bogotá'),
          nullif(v_meta->>'localidad',''), nullif(v_meta->>'direccion',''))
  returning "idDireccion" into v_dir;

  insert into "usuarios"("identificacion","nombre","apellidos","correoElectronico","telefono",
                         "rol_idRol","direccion_idDireccion","auth_id")
  values (v_ident,
          coalesce(nullif(v_meta->>'nombre',''), split_part(new.email, '@', 1)),
          coalesce(v_meta->>'apellido', ''),
          new.email,
          nullif(v_meta->>'telefono',''),
          (select "idRol" from "roles" where lower("nombreRol") = 'cliente'),
          v_dir,
          new.id);
  return new;
end $$;

create trigger kronos_on_auth_user_created
  after insert on auth.users
  for each row execute function public.kronos_handle_new_auth_user();

-- 8.2 Todo usuario con rol Cliente tiene su fila en `clientes`
create or replace function public.kronos_usuario_crea_cliente()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from "roles" r where r."idRol" = new."rol_idRol" and lower(r."nombreRol") = 'cliente') then
    insert into "clientes"("usuario_identificacion") values (new."identificacion")
    on conflict ("usuario_identificacion") do nothing;
  end if;
  return new;
end $$;

create trigger trg_usuario_crea_cliente
  after insert on "usuarios"
  for each row execute function public.kronos_usuario_crea_cliente();

-- 8.3 Movimiento: completa datos y aplica el stock (única vía para cambiar stock)
create or replace function public.kronos_movimiento_antes()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new."precioUnitario" is null then
    select i."precioVenta" into new."precioUnitario" from "inventarios" i where i."id" = new."inventario_codInventario";
  end if;
  new."subtotal" := coalesce(new."subtotal", new."cantidad" * coalesce(new."precioUnitario", 0));
  new."usuario_identificacion" := coalesce(new."usuario_identificacion", public.kronos_mi_identificacion());
  return new;
end $$;

create trigger trg_movimiento_antes
  before insert on "movimientos"
  for each row execute function public.kronos_movimiento_antes();

create or replace function public.kronos_movimiento_aplica_stock()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_inv   "inventarios"%rowtype;
  v_delta integer;
begin
  v_delta := case
    when new."tipoMovimiento" in (1,3,5) then  new."cantidad"
    when new."tipoMovimiento" in (2,4)   then -new."cantidad"
    else 0 end;

  select * into v_inv from "inventarios" where "id" = new."inventario_codInventario" for update;

  if v_inv."stock" + v_delta < 0 then
    raise exception 'Stock insuficiente de "%": solo hay % disponible(s).', v_inv."nombre", v_inv."stock";
  end if;

  update "inventarios" set "stock" = v_inv."stock" + v_delta where "id" = v_inv."id";
  return new;
end $$;

create trigger trg_movimiento_aplica_stock
  after insert on "movimientos"
  for each row execute function public.kronos_movimiento_aplica_stock();

-- 8.4 Alertas de stock (se crean / actualizan / resuelven solas)
create or replace function public.kronos_inventario_alerta()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_msg text;
begin
  if new."stock" <= new."umbralMinimo" then
    v_msg := case when new."stock" <= 0
      then format('Agotado: "%s" no tiene unidades disponibles.', new."nombre")
      else format('Bajo stock: "%s" tiene %s unidad(es) y su umbral mínimo es %s.', new."nombre", new."stock", new."umbralMinimo")
    end;
    if exists (select 1 from "alertas" a where a."inventario_codInventario" = new."id" and a."estado" = 'pendiente') then
      update "alertas" set "mensaje" = v_msg, "fechaAlerta" = now()
      where "inventario_codInventario" = new."id" and "estado" = 'pendiente';
    else
      insert into "alertas"("estado","mensaje","fechaAlerta","inventario_codInventario")
      values ('pendiente', v_msg, now(), new."id");
    end if;
  else
    update "alertas" set "estado" = 'resuelta'
    where "inventario_codInventario" = new."id" and "estado" = 'pendiente';
  end if;
  return new;
end $$;

create trigger trg_inventario_alerta
  after insert or update of "stock", "umbralMinimo", "nombre" on "inventarios"
  for each row execute function public.kronos_inventario_alerta();

-- 8.5 Venta a cliente -> salida automática de inventario (movimiento tipo 4)
create or replace function public.kronos_detalle_venta_salida()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into "movimientos"("fechaMovimiento","precioUnitario","cantidad","subtotal","tipoMovimiento",
                            "usuario_identificacion","inventario_codInventario","detalleVenta_idDetalleVenta")
  values (now(), new."precioUnitario", new."cantidad", new."subTotal", 4,
