-- ============================================================
-- Pegar COMPLETO en Supabase > SQL Editor y ejecutar (Run).
--
--  ⚠️  BORRA todas las tablas anteriores del proyecto (perfiles,
--      productos, ordenes_compra, reportes_generados, movimientos,
--      proveedores, categorias, garantias, ventas...) y sus datos.
--      Los usuarios de Authentication NO se borran.
--
-- Las 16 tablas del diagrama (nombres y columnas tal cual):
--   authenticacion : roles, usuarios, direcciones, clientes
--   proveedores    : proveedores, ordenesCompra
--   inventario     : inventarios, alertas, movimientos
--   materiales     : categorias, unidadVentas, marcas
--   garantías/vtas : ventas, detalleVentas, garantias, garantiaBitacoras
--
-- Diferencias mínimas con el diagrama (necesarias para que funcione
-- con Supabase Auth y con el front):
--   1) usuarios."auth_id"  (uuid)  -> vincula la fila con auth.users.
--      usuarios."contrasena" se conserva pero queda NULL: la
--      contraseña la guarda Supabase Auth (hasheada), nunca aquí.
--   2) usuarios."identificacion" es BIGINT (una cédula de 10 dígitos
--      puede pasar del máximo de un INT).
--   3) ordenesCompra."observacion" y ventas."observacion" (TEXT):
--      motivo de rechazo / nota del vendedor que el front ya mostraba.
--   4) Textos libres (motivo, observacion, comentario, mensaje) son
--      TEXT en vez de VARCHAR(45) para que no se corten; inventarios.nombre
--      y usuarios.nombre son VARCHAR(120)/(100) (nombres de producto o de
--      empresa proveedora que pasan de 45 caracteres).
--   5) imagenProducto y evidenciaImg son TEXT (URL o data-URL) en vez
--      de MEDIUMBLOB, que no existe en PostgreSQL.
--   6) "umbralMinimo" (el diagrama dice "umblalMinimo": typo).
--
-- tipoMovimiento (INT):
--   1 = Entrada manual      2 = Salida manual
--   3 = Entrada por orden de compra confirmada
--   4 = Salida por venta a cliente
--   5 = Devolución de stock (venta rechazada)
-- ============================================================


