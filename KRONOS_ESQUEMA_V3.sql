-- 8.8 Garantías: vigencia (90 días desde la venta) + bitácora automática
create or replace function public.kronos_garantia_antes()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_fecha_venta timestamptz;
begin
  select v."fechaVenta" into v_fecha_venta
  from "detalleVentas" d join "ventas" v on v."idVenta" = d."venta_idVenta"
  where d."idDetalleVenta" = new."detalleventa_idDetalleVenta";

  new."fechaInicio" := coalesce(v_fecha_venta, new."fechaInicio", now());
  new."fechaFin"    := coalesce(new."fechaFin", new."fechaInicio" + interval '90 days');
  return new;
end $$;

